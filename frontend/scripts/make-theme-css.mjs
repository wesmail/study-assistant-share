// Writes src/theme.css: the dark theme as Tailwind's own palette turned over.
//
//   node scripts/make-theme-css.mjs
//
// Tailwind 4 draws every colour class from a CSS variable (--color-stone-50 and so on), so the
// dark theme redefines those variables instead of adding dark: classes to every component:
// each palette is reversed (50 <-> 950, 100 <-> 900, ... 500 stays), keeping its hue, and white
// (panels, cards) becomes stone-900, a step above the page's stone-950. Text on a coloured
// button turns dark as its background turns light, so contrast holds both ways.
//
// .keep-light restores the light values inside it: a PDF page is white in either theme, and
// highlights and notes drawn over it keep the colours they were chosen with.
// Run again after a Tailwind upgrade or when a component starts using another palette.
import { readFileSync, writeFileSync } from "node:fs";

const PALETTES = ["stone", "teal", "amber", "red", "sky", "indigo", "lime", "pink", "yellow"];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const source = readFileSync(new URL("../node_modules/tailwindcss/theme.css", import.meta.url), "utf8");

function value(name) {
  const found = new RegExp(`--color-${name}:\\s*([^;]+);`).exec(source);
  if (!found) throw new Error(`no --color-${name} in Tailwind's theme.css`);
  return found[1].trim();
}

const dark = [], light = [];
for (const palette of PALETTES) {
  SHADES.forEach((shade, index) => {
    const mirror = SHADES[SHADES.length - 1 - index];
    dark.push(`  --color-${palette}-${shade}: ${value(`${palette}-${mirror}`)};`);
    light.push(`  --color-${palette}-${shade}: ${value(`${palette}-${shade}`)};`);
  });
}
dark.push(`  --color-white: ${value("stone-900")};`, `  --color-black: ${value("white")};`);
light.push(`  --color-white: ${value("white")};`, `  --color-black: ${value("black")};`);

const css = `/* Generated by scripts/make-theme-css.mjs from Tailwind's palette: don't edit by hand. */

:root[data-theme="dark"] {
${dark.join("\n")}
}

:root[data-theme="dark"] .keep-light {
${light.join("\n")}
  color-scheme: light;
}
`;
writeFileSync(new URL("../src/theme.css", import.meta.url), css);
console.log(`src/theme.css: ${PALETTES.length} palettes, ${dark.length} variables`);
